	private final String numistaValue;
	private final String serviceId;
	private final String label;

	NumistaGradingMark(String numistaValue, String serviceId, String label) {
		this.numistaValue = numistaValue;
		this.serviceId = serviceId;
		this.label = label;
	}

	public String getNumistaValue() {
		return numistaValue;
	}

	/** {@link NumistaGradingService} numista value ({@code data-service-id}). */
	public String getServiceId() {
		return serviceId;
	}

	public String getLabel() {
		return label;
	}

	public Optional<NumistaGradingService> getGradingService() {
		return NumistaGradingService.fromNumistaValue(serviceId);
	}

	public static Optional<NumistaGradingMark> fromNumistaValue(String value) {
		if (!StringUtils.hasText(value) || "0".equals(value.trim())) {
			return Optional.empty();
		}
		String trimmed = value.trim();
		return Arrays.stream(values())
				.filter(m -> m.numistaValue.equals(trimmed))
				.findFirst();
	}

	public static Optional<NumistaGradingMark> fromNumistaValueAndService(
			String value, NumistaGradingService gradingService) {
		if (!StringUtils.hasText(value) || gradingService == null || "0".equals(value.trim())) {
			return Optional.empty();
		}
		String trimmed = value.trim();
		String serviceValue = gradingService.getNumistaValue();
		return Arrays.stream(values())
				.filter(m -> m.numistaValue.equals(trimmed) && m.serviceId.equals(serviceValue))
				.findFirst();
	}

	public static List<NumistaGradingMark> forService(NumistaGradingService gradingService) {
		if (gradingService == null) {
			return List.of();
		}
		String serviceValue = gradingService.getNumistaValue();
		return Arrays.stream(values())
				.filter(m -> m.serviceId.equals(serviceValue))
				.toList();
	}

	public static Optional<NumistaGradingMark> fromLabelAndService(String label, NumistaGradingService gradingService) {
		if (!StringUtils.hasText(label) || gradingService == null) {
			return Optional.empty();
		}
		String trimmed = label.trim();
		String serviceValue = gradingService.getNumistaValue();
		return Arrays.stream(values())
				.filter(m -> m.serviceId.equals(serviceValue) && m.label.equalsIgnoreCase(trimmed))
				.findFirst();
	}
